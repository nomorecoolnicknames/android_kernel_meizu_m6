static void push_table(struct LCM_setting_table *table, unsigned int count,
		       unsigned char force_update)
{
	unsigned int i;

	for (i = 0; i < count; i++) {
		unsigned int cmd = table[i].cmd;

		switch (cmd) {
		case REGFLAG_DELAY:
			MDELAY(table[i].count);
			break;
		case REGFLAG_UDELAY:
			UDELAY(table[i].count);
			break;
		case REGFLAG_END_OF_TABLE:
			break;
		default:
			dsi_set_cmdq_V2(cmd, table[i].count,
					table[i].para_list, force_update);
			break;
		}
	}
}

static void lcm_set_util_funcs(const LCM_UTIL_FUNCS *util)
{
	memcpy(&lcm_util, util, sizeof(LCM_UTIL_FUNCS));
}

static void lcm_get_params(LCM_PARAMS *params)
{
	memset(params, 0, sizeof(LCM_PARAMS));

	params->type   = LCM_TYPE_DSI;
	params->width  = FRAME_WIDTH;
	params->height = FRAME_HEIGHT;

	params->dsi.mode     = SYNC_EVENT_VDO_MODE;
	params->dsi.LANE_NUM = LCM_FOUR_LANE;

	params->dsi.data_format.color_order = LCM_COLOR_ORDER_RGB;
	params->dsi.data_format.trans_seq   = LCM_DSI_TRANS_SEQ_MSB_FIRST;
	params->dsi.data_format.padding     = LCM_DSI_PADDING_ON_LSB;
	params->dsi.data_format.format      = LCM_DSI_FORMAT_RGB888;

	params->dsi.PS          = LCM_PACKED_PS_24BIT_RGB888;
	params->dsi.packet_size = 256;
	params->dsi.word_count  = 2160;

	/* stock lcm_get_params store offsets:
	 *   [520] vsa  [524] vbp  [528] vfp  [536] vertical_active_line
	 *   [540] hsa  [544] hbp  [548] hfp  [556] horizontal_active_pixel
	 */
	params->dsi.vertical_sync_active    = 4;
	params->dsi.vertical_backporch      = 16;
	params->dsi.vertical_frontporch     = 16;
	params->dsi.vertical_active_line    = FRAME_HEIGHT;

	params->dsi.horizontal_sync_active  = 4;
	params->dsi.horizontal_backporch    = 32;
	params->dsi.horizontal_frontporch   = 32;
	params->dsi.horizontal_active_pixel = FRAME_WIDTH;

	params->dsi.PLL_CLOCK   = 220;		/* [656] */
	params->dsi.ssc_disable = 1;		/* [672] */

	params->dsi.esd_check_enable = 1;
	params->physical_width  = 65;
	params->physical_height = 130;
}

static void lcm_init_power(void)
{
	/* stock lcm_init_power: reset low, bring up the positive rail, program
	 * the TPS65132 VPOS register, settle, then the negative rail + VNEG. */
	SET_RESET_PIN(0);
	set_gpio_lcd_enp(1);
	tps65132_write_bytes(0x00, 0x12);
	MDELAY(10);
	set_gpio_lcd_enn(1);
	tps65132_write_bytes(0x01, 0x12);
	MDELAY(5);
	LCM_LOGI("%s\n", __func__);
}

static void lcm_suspend_power(void)
{
	LCM_LOGI("%s\n", __func__);
}

static void lcm_resume_power(void)
{
	lcm_init_power();
	LCM_LOGI("%s\n", __func__);
}

static void lcm_init(void)
{
	/* stock reset pulse */
	SET_RESET_PIN(1);
	MDELAY(2);
	SET_RESET_PIN(0);
	MDELAY(5);
	SET_RESET_PIN(1);
	MDELAY(5);
	push_table(init_setting,
		   sizeof(init_setting) / sizeof(struct LCM_setting_table), 1);
	LCM_LOGI("%s\n", __func__);
}

static void lcm_suspend(void)
{
	push_table(suspend_setting,
		   sizeof(suspend_setting) / sizeof(struct LCM_setting_table), 1);
	/* stock tail: reset(0) + rails off */
	SET_RESET_PIN(0);
	MDELAY(2);
	set_gpio_lcd_enn(0);
	MDELAY(1);
	set_gpio_lcd_enp(0);
	MDELAY(2);
	LCM_LOGI("%s\n", __func__);
}

static void lcm_resume(void)
{
	lcm_init();
	LCM_LOGI("%s\n", __func__);
}

static unsigned int lcm_compare_id(void)
{
	/* Panel selection does NOT go through compare_id: disp_lcm_probe()
	 * matches lcm_drv->name against the name LK passes.  Stock's
	 * compare_id for this panel still exists, but reproducing its DSI
	 * read-back without hardware to test against would be guesswork, so
	 * return "match" and let the name decide.  Revisit once a real M6T
	 * is on the bench. */
	return 1;
}

