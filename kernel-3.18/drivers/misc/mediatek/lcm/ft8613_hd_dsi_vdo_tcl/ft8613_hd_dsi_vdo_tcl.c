/*
 * M6T stock LCM driver: FocalTech FT8613, 720x1440 18:9 DSI video mode.
 *
 * RE-ported from the Meizu/Flyme M6T stock kernel (Linux 3.18.35+,
 * built 2019-02-18) recovered at
 * /srv/forge/android/meizu_m6t/reverse/vmlinux.recovered.elf.
 *
 * WHY THIS FILE EXISTS
 * --------------------
 * The stock kernel registers THREE LCM drivers and MTK's disp_lcm_probe()
 * picks one by strcmp(lcm_drv->name, <name passed by LK>).  Proven from
 * the recovered image:
 *
 *   lcm_count            @0xffffffc00116cf38 = 3
 *   lcm_driver_list[0]   @0xffffffc00116cf40 -> ft8613_hd_dsi_vdo_tcl
 *   lcm_driver_list[1]   @0xffffffc00116cf48 -> nt36525_hd_dsi_vdo_djn
 *   lcm_driver_list[2]   @0xffffffc00116cf50 -> hx83102b_hd_dsi_vdo_lide
 *
 * With only one driver compiled in, disp_lcm_probe() takes the
 * _lcm_count()==1 branch, hits "FATAL ERROR!!!LCM Driver defined in
 * kernel(%s) is different with LK(%s)" and returns NULL -> black screen
 * on every handset whose panel vendor differs.  So all three names must
 * exist in the kernel; this file supplies one of the two that were
 * missing.
 *
 * THE NAME STRING IS THE CONTRACT.  Do not "tidy" .name below.
 *
 * DATA PROVENANCE (all FACT, decoded not guessed)
 *   LCM_DRIVER struct     @0xffffffc00116f638
 *   init_setting table    @0xffffffc00116d160  (131 entries)
 *   suspend_setting table @0xffffffc00116d040  (4 entries)
 * Table entry layout u32 cmd / u8 count / u8 para_list[64], stride 0x48,
 * proven by disassembling push_table.constprop.*.  Timing values were
 * read from the lcm_get_params store offsets and resolved against
 * offsetof() compiled from this tree's lcm_drv.h.
 *
 * NOT RUNTIME-VERIFIED: no M6T hardware was attached when this was
 * written.  compare_id() is deliberately a stub (see below).
 */

